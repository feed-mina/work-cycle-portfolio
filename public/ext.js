/* ext.js — 확장점 (extension point)
 *
 * 이 파일은 work-cycle에서 의도적으로 비어 있습니다.
 * 모든 화면(public/*.html)이 <script src="/ext.js" defer>로 이 파일을 부르지만
 * 회사 앱에서는 아무 일도 하지 않습니다.
 *
 * 왜 비워 두는가
 * ─────────────────────────────────────────────────────────────
 * work-cycle을 upstream으로 받아 쓰는 저장소(private-cycle-work 등)가
 * 화면을 덧붙일 때, 회사 화면 HTML 6개를 고치지 않고 이 파일 하나만
 * 통째로 교체하면 되도록 하기 위해서입니다.
 *
 * 상단 탭은 6개 HTML에 같은 문자열로 하드코딩되어 있어서, 파생 저장소가
 * 그 줄에 탭을 끼워 넣으면 upstream이 탭을 한 번 고칠 때마다 6곳이
 * 동시에 충돌합니다. 이 파일은 upstream이 건드리지 않으므로,
 * 파생 쪽에서 덮어써도 merge 충돌이 구조적으로 생기지 않습니다.
 *
 * 규칙
 * ─────────────────────────────────────────────────────────────
 * - work-cycle에서는 이 파일에 코드를 넣지 않습니다. 회사 기능은
 *   기존 js(acc/principles/edit/quick)나 화면별 인라인 스크립트에 둡니다.
 * - 파생 저장소는 이 파일을 통째로 교체합니다(부분 수정 금지).
 * - 실행 시점은 defer라 DOM 파싱이 끝난 뒤입니다.
 */
